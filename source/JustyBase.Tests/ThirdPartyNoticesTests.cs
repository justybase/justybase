using System.IO;

namespace JustyBase.Tests;

/// <summary>
/// The About window shows the generated third-party inventory from an embedded
/// resource. Guard the resource name and the generated table header so the
/// dialog cannot silently ship an empty or stale document.
/// </summary>
public sealed class ThirdPartyNoticesTests
{
    [Fact]
    public void ThirdPartyNotices_AreEmbeddedInTheApplicationAssembly()
    {
        var assembly = typeof(JustyBase.Views.About).Assembly;

        using var stream = assembly.GetManifestResourceStream("JustyBase.THIRD_PARTY_NOTICES.md");

        Assert.NotNull(stream);
        using var reader = new StreamReader(stream!);
        var text = reader.ReadToEnd();

        Assert.Contains("# Third-party notices", text, StringComparison.Ordinal);
        Assert.Contains("| Package | Version | License | Project |", text, StringComparison.Ordinal);
        Assert.Contains("Do not edit this file manually.", text, StringComparison.Ordinal);
    }
}
